"""SaaS connectors for Autonomy: connect once, then sync, listen and stay healthy with no one watching.

Read `docs/v2/CONNECTORS.md` first. The pieces:

* `base` - the connector contract (`SaasConnector`, `ConnectorCapabilities`, `StreamSpec`, ...)
  and the failure classes that tell the engine what to do;
* `http` - the polite client (pacing, pinned versions, retries with backoff and jitter,
  `Retry-After`, idempotency keys, pagination helpers, secret-free errors);
* `oauth` - authorization code flow with state and PKCE, code exchange, refresh;
* `tokens` - the encrypted token vault and the lease-locked, keep-alive token manager;
* `store` - every piece of connector state in SQL (positions, runs, leases, deliveries, ...);
* `sync` - the engine: connect, two-lane sync (live + history), ingest, schedule, fail well;
* `webhooks` - verify, dedupe, queue and answer fast; process later;
* `health` - freshness, row drops, drift, error streaks; "may we act?"; one alert per problem;
* `registry` - the catalogue for the API and the Connect screen;
* `wiring` - how it plugs in: the production registry, the jobs after a connect, the worker's
  handlers, and send-through-the-customer's-tool providers with our own SES as the fallback;
* `shopify`, `klaviyo` - the first two platforms (imported on their own, or through the registry).

Nothing here imports httpx, cryptography or v1's `engine` at module scope.
"""

