"""The intake rules on a grid of text cells (Plan L M150, DEC-1502): no storage, no pandas frames.

A file reaches these functions as records, each a list of cell texts: a CSV's `csv.reader` records or
a sheet's rows turned into text by `engine.intake.excel.cell_text`. Both sources go through the same
rules, so an Excel export and the CSV saved from it are read alike.

The rules are written to leave an ordinary file alone. Each one fires only on a shape a report export
or a hand-kept sheet has and a table does not:

* **The header row** moves down only when every row above it is *title-like* (at most two filled cells,
  and fewer than the table is wide) and the row found is *header-like* (at least two, and at least
  half the width, filled cells, none of them a number) with a row of data under it. A file whose first
  row has three or more filled cells keeps it as its header, whatever it says, and so does one whose
  first row is header-like itself.
* **Two header rows** are joined only when the header repeats a name and the row above it has at least
  two filled cells: `Q1` / `Revenue` becomes `Q1 Revenue`. Only the repeated names are joined, and a
  column named only in the upper row (`id` above an empty cell) takes that name.
* **A trailing row** is left out only when its first filled cell (in one of the first three columns)
  is a whole total word (`Grand Total`, `Sub-total:`), or it is a single cell of three or more words or
  with a colon in a table at least three columns wide (`Generated by CRM on 3 Oct`). At most
  `max_footer_rows`, and never the last data row left.
* **Missing words** (`-`, `unknown`, `#DIV/0!`) are read as empty only in a column whose other values
  the engine's own type rule (`engine.stages.ingest.infer_column_type`) reads as numbers, dates or yes/no.
"""

from __future__ import annotations

import math
import re
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Final

from engine.config import ColumnType
from engine.intake.config import IntakeConfig
from engine.intake.contracts import RenamedColumn

__all__ = [
    "TYPED_COLUMN_TYPES",
    "HeaderDecision",
    "find_footer",
    "find_header",
    "is_empty_record",
    "keep_columns",
    "missing_word_columns",
    "name_columns",
    "nonempty",
    "table_width",
]

WIDTH_ROWS: Final[int] = 200
"""Rows the table's width is measured over."""

MAX_TITLE_CELLS: Final[int] = 2
"""A row above the header holds at most this many filled cells."""

DATA_LOOKAHEAD: Final[int] = 5
"""Rows after a header-like row searched for the data that proves it is a header."""

FIRST_COLUMNS: Final[int] = 3
"""A total word or a note sits in one of the first this many columns."""

TYPED_COLUMN_TYPES: Final[frozenset[ColumnType]] = frozenset(
    {ColumnType.INTEGER, ColumnType.FLOAT, ColumnType.DATE, ColumnType.DATETIME, ColumnType.BOOLEAN}
)
"""Column types in which a missing word means "no value"."""

_NUMBER: Final[re.Pattern[str]] = re.compile(r"^[+-]?(\d[\d,]*\.?\d*|\.\d+)(e[+-]?\d+)?%?$", re.IGNORECASE)
_PARENTHESIS_TAIL: Final[re.Pattern[str]] = re.compile(r"\s*\(.*\)\s*$")


def nonempty(record: Sequence[str]) -> list[int]:
    """Positions of the cells holding anything but spaces."""
    return [index for index, cell in enumerate(record) if cell.strip()]


def is_empty_record(record: Sequence[str]) -> bool:
    return not any(cell.strip() for cell in record)


def _is_number(cell: str) -> bool:
    return bool(_NUMBER.match(cell.strip().replace(" ", "")))


def table_width(records: Sequence[Sequence[str]]) -> int:
    """The most filled cells any of the first `WIDTH_ROWS` records holds."""
    return max((len(nonempty(record)) for record in records[:WIDTH_ROWS]), default=0)


def _half(width: int) -> int:
    return max(1, math.ceil(width / 2))


def _title_like(record: Sequence[str], width: int) -> bool:
    filled = len(nonempty(record))
    return filled <= MAX_TITLE_CELLS and filled < width


def _header_like(record: Sequence[str], width: int) -> bool:
    cells = [record[index] for index in nonempty(record)]
    return len(cells) >= 2 and len(cells) >= _half(width) and not any(_is_number(cell) for cell in cells)


def _data_follows(records: Sequence[Sequence[str]], index: int) -> bool:
    need = _half(len(nonempty(records[index])))
    for record in records[index + 1 : index + 1 + DATA_LOOKAHEAD]:
        filled = len(nonempty(record))
        if filled:
            return filled >= need
    return False


def _repeats(record: Sequence[str]) -> bool:
    names = [record[index].strip() for index in nonempty(record)]
    return len(names) != len(set(names))


@dataclass(frozen=True)
class HeaderDecision:
    """Where the column names are, as record indexes of the grid."""

    header_index: int = 0
    group_index: int | None = None
    """The row above the header whose labels are joined to repeated names, when there is one."""

    @property
    def data_start(self) -> int:
        return self.header_index + 1

    @property
    def rows_above(self) -> int:
        """Records above the names that are not part of them."""
        return self.header_index if self.group_index is None else self.group_index

    @property
    def moved(self) -> bool:
        return self.header_index > 0


def find_header(records: Sequence[Sequence[str]], config: IntakeConfig) -> HeaderDecision:
    """The row holding the column names; the first row unless the rules in the module docstring say otherwise."""
    if not records:
        return HeaderDecision()
    width = table_width(records)
    header: int | None = None
    for index, record in enumerate(records[: config.max_header_search_rows]):
        if _header_like(record, width) and _data_follows(records, index):
            header = index
            break
        if _group_over(records, index, width):
            return HeaderDecision(header_index=index + 1, group_index=index)
        if not _title_like(record, width):
            return _joined(records, 0)
    if header is None:
        return HeaderDecision()
    if _group_over(records, header, width):
        return HeaderDecision(header_index=header + 1, group_index=header)
    return _joined(records, header)


def _group_over(records: Sequence[Sequence[str]], index: int, width: int) -> bool:
    """True when record `index` is a row of group labels over a row that repeats names (`Q1` over `Revenue`).

    The two rows are judged together, as Excel lays them out: a column outside any group keeps its
    name in the upper row (a cell merged downwards), so the lower row may be sparse. Together they
    must name at least half the table, the lower row must repeat a name and hold no number, and the
    upper row must be empty somewhere above a lower name (the merged group cell's shadow).
    """
    nxt = index + 1
    if nxt >= len(records):
        return False
    upper, lower = records[index], records[nxt]
    lower_cells = [lower[position].strip() for position in nonempty(lower)]
    named = set(nonempty(upper)) | set(nonempty(lower))
    if (
        len(nonempty(upper)) < 2
        or len(lower_cells) < 2
        or any(_is_number(cell) for cell in lower_cells)
        or not _repeats(lower)
        or len(named) < _half(width)
        or not _has_gaps(upper, lower)
    ):
        return False
    need = _half(len(named))
    for record in records[nxt + 1 : nxt + 1 + DATA_LOOKAHEAD]:
        filled = len(nonempty(record))
        if filled:
            return filled >= need
    return False


def _joined(records: Sequence[Sequence[str]], header: int) -> HeaderDecision:
    """`header`, with the row above it as its group row when the header repeats a name."""
    if header >= 1 and _repeats(records[header]) and len(nonempty(records[header - 1])) >= 2:
        return HeaderDecision(header_index=header, group_index=header - 1)
    return HeaderDecision(header_index=header)


def _has_gaps(group: Sequence[str], header: Sequence[str]) -> bool:
    """True when the group row is empty somewhere under the header's span: a merged cell's shadow."""
    filled = nonempty(header)
    if not filled:
        return False
    first = min(nonempty(group), default=0)
    return any(index >= first and (index >= len(group) or not group[index].strip()) for index in filled)


def keep_columns(header: Sequence[str], sample: Sequence[Sequence[str]]) -> tuple[list[int], int]:
    """Positions kept, and how many were left out: a column with no name and no value in `sample`."""
    width = max([len(header), *(len(record) for record in sample)], default=0)
    filled: set[int] = {index for record in sample for index in nonempty(record)}
    kept = [
        index for index in range(width) if (index < len(header) and header[index].strip()) or index in filled
    ]
    return kept, width - len(kept)


def name_columns(
    header: Sequence[str], group: Sequence[str] | None, kept: Sequence[int]
) -> tuple[list[str], list[RenamedColumn]]:
    """The names of the kept columns: joined, filled in and made unique, with every change recorded.

    A blank name becomes `Unnamed: <position>`, the name pandas gives it, so a file read with and
    without intake names that column alike. A repeated name gets `_2`, `_3`, ... (stripped names
    compared, as `engine.stages.ingest` compares them).
    """
    raw = [header[index] if index < len(header) else "" for index in kept]
    names: list[str] = list(raw)
    renamed: list[RenamedColumn] = []
    if group is not None:
        counts: dict[str, int] = {}
        for name in raw:
            counts[name.strip()] = counts.get(name.strip(), 0) + 1
        label = ""
        labels: dict[int, str] = {}
        for index in range(max(kept, default=-1) + 1):
            if index < len(group) and group[index].strip():
                label = group[index].strip()
            labels[index] = label
        for out, index in enumerate(kept):
            stripped = raw[out].strip()
            own = group[index].strip() if index < len(group) else ""
            if not stripped and own:
                names[out] = own
                renamed.append(RenamedColumn(position=out + 1, original=raw[out], name=own, reason="joined"))
            elif stripped and counts[stripped] > 1 and labels.get(index):
                names[out] = f"{labels[index]} {stripped}"
                renamed.append(
                    RenamedColumn(position=out + 1, original=raw[out], name=names[out], reason="joined")
                )
    for out, name in enumerate(names):
        if not name.strip():
            names[out] = f"Unnamed: {out}"
            renamed.append(
                RenamedColumn(position=out + 1, original=raw[out], name=names[out], reason="blank")
            )
    taken = {name.strip() for name in names}
    seen: set[str] = set()
    for out, name in enumerate(names):
        stripped = name.strip()
        if stripped in seen:
            suffix = 2
            while f"{stripped}_{suffix}" in taken:
                suffix += 1
            names[out] = f"{stripped}_{suffix}"
            taken.add(names[out])
            renamed.append(
                RenamedColumn(position=out + 1, original=raw[out], name=names[out], reason="repeated")
            )
        seen.add(stripped)
    return names, renamed


def _total_word(cell: str, words: frozenset[str]) -> bool:
    text = _PARENTHESIS_TAIL.sub("", cell.strip().casefold()).rstrip(": ").strip()
    return text in words


def _footer_like(record: Sequence[str], width: int, words: frozenset[str]) -> bool:
    filled = nonempty(record)
    if not filled or filled[0] >= FIRST_COLUMNS:
        return False
    first = record[filled[0]].strip()
    if _total_word(first, words):
        return True
    return (
        width >= 3
        and len(filled) == 1
        and not _is_number(first)
        and (len(first.split()) >= 3 or ":" in first)
    )


def find_footer(
    records: Sequence[Sequence[str]], width: int, config: IntakeConfig, *, keep_at_least: int = 1
) -> tuple[int, list[str]]:
    """How many trailing records to leave out, and the first cell of each footer row among them.

    Empty records between and after footer rows are part of the count. Nothing is left out when no
    footer row is found, or when leaving them out would leave fewer than `keep_at_least` data rows.
    """
    words = frozenset(config.total_words)
    found: list[str] = []
    span = 0
    last_footer = 0
    for position, record in enumerate(reversed(records), start=1):
        if is_empty_record(record):
            continue
        if len(found) >= config.max_footer_rows or not _footer_like(record, width, words):
            break
        found.append(record[nonempty(record)[0]].strip())
        last_footer = position
    span = last_footer
    if not found:
        return 0, []
    remaining = sum(1 for record in records[: len(records) - span] if not is_empty_record(record))
    if remaining < keep_at_least:
        return 0, []
    return span, list(reversed(found))


def missing_word_columns(
    sample: Sequence[Sequence[str]], width: int, words: frozenset[str]
) -> tuple[list[int], dict[int, set[str]]]:
    """Columns (of `width`) whose non-missing values are numbers, dates or yes/no, and the words seen in each.

    "Numbers" is pandas' own test - every other value converts - because that is what makes the column
    read as numbers once the words are gone; dates and yes/no follow the engine's type rule.

    Every such column has its missing words emptied, whether or not the sample holds one; the second
    value says which columns the sample showed words in (a rewrite is needed only when one did).
    """
    import pandas as pd

    from engine.stages.ingest import infer_column_type

    typed: list[int] = []
    seen: dict[int, set[str]] = {}
    for column in range(width):
        values = [
            record[column].strip() for record in sample if column < len(record) and record[column].strip()
        ]
        found = {value.casefold() for value in values if value.casefold() in words}
        others = [value for value in values if value.casefold() not in words]
        if not others:
            continue
        series = pd.Series(others, dtype=object)
        all_numbers = bool(pd.to_numeric(series, errors="coerce").notna().all())
        if all_numbers or infer_column_type(series) in TYPED_COLUMN_TYPES:
            typed.append(column)
            if found:
                seen[column] = found
    return typed, seen
