"""The messy-file bench of Plan L M150: thirty files shaped like real exports, each with several problems at once.

No client data: every file is built here from one small customer table and a list of the problems a
case adds - title rows, two header rows, a repeated name, totals and notes at the end, empty rows,
missing words, phantom columns, a semicolon delimiter, a Windows code page, a workbook with other
sheets. `expected_columns` says what the columns must be called once intake has read the file.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any, Literal

ROWS = 25
"""Customers in every case: more than the engine's smallest sample, small enough to stay fast."""


@dataclass(frozen=True)
class Case:
    name: str
    fmt: Literal["csv", "xlsx"] = "csv"
    titles: int = 0
    grouped: bool = False
    repeated: bool = False
    footer: Literal["", "total", "total_note"] = ""
    empty_rows: bool = False
    missing: bool = False
    phantom: bool = False
    delimiter: str = ","
    encoding: str = "utf-8"
    other_sheets: bool = False
    seed: int = 0
    extra: dict[str, str] = field(default_factory=dict)

    @property
    def expected_columns(self) -> list[str]:
        if self.grouped:
            columns = ["id", "plan", "Q1 spend", "Q1 orders", "Q2 spend", "Q2 orders", "joined", "active"]
        else:
            columns = ["id", "plan", "tenure", "spend", "joined", "active"]
        if self.repeated:
            columns.append("plan_2")
        return columns


def _customers(case: Case) -> list[list[object]]:
    rows: list[list[object]] = []
    for index in range(ROWS):
        number = index + 1 + case.seed * 100
        plan = ["Gold", "Silver", "Bronze"][index % 3]
        if case.encoding == "cp1252" and index % 3 == 0:
            plan = "Café"
        tenure: object = (index * 7) % 60 + 1
        spend: object = round(100 + index * 13.5 + case.seed, 2)
        if case.missing and index % 6 == 1:
            tenure = "-"
        if case.missing and index % 8 == 2:
            spend = "unknown"
        joined: object = date(2024, 1 + index % 12, 1 + index % 27)
        active: object = "Y" if index % 2 else "N"
        if case.missing and index % 10 == 3:
            active = "N/A"
        if case.grouped:
            row: list[object] = [f"C{number}", plan, spend, index % 5, tenure, index % 4, joined, active]
        else:
            row = [f"C{number}", plan, tenure, spend, joined, active]
        if case.repeated:
            row.append(plan.upper())
        rows.append(row)
    return rows


def grid(case: Case) -> list[list[object]]:
    """The sheet as a person would see it: titles, header rows, data, then footers."""
    width = len(case.expected_columns) + (2 if case.phantom else 0)
    pad = [""] * (2 if case.phantom else 0)
    out: list[list[Any]] = []
    titles = ["Customer export", f"Generated on 2026-10-0{1 + case.seed % 9}", ""]
    for line in titles[: case.titles]:
        out.append([line] + [""] * (width - 1))
    if case.grouped:
        out.append(
            ["id", "plan", "Q1", "", "Q2", "", "joined", "active"] + (["plan"] if case.repeated else []) + pad
        )
        out.append(
            ["", "", "spend", "orders", "spend", "orders", "", ""] + ([""] if case.repeated else []) + pad
        )
    else:
        out.append(
            ["id", "plan", "tenure", "spend", "joined", "active"] + (["plan"] if case.repeated else []) + pad
        )
    for index, row in enumerate(_customers(case)):
        out.append(row + pad)
        if case.empty_rows and index in (4, 11):
            out.append([""] * width)
    if case.footer:
        out.append(["Grand Total"] + [""] * (width - 1))
    if case.footer == "total_note":
        out.append([""] * width)
        out.append(["Generated by the CRM export tool"] + [""] * (width - 1))
    return out


def _text(value: object) -> str:
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def write(case: Case, directory: Path) -> Path:
    """The case's file under `directory`, named as a client would name it."""
    rows = grid(case)
    if case.fmt == "xlsx":
        from openpyxl import Workbook  # type: ignore[import-untyped]

        book = Workbook()
        first = book.active
        if case.other_sheets:
            first.title = "Read me"
            first.append(["This workbook was exported from the CRM."])
            sheet = book.create_sheet("Customers")
            summary = book.create_sheet("Summary")
            summary.append(["plan", "customers"])
            summary.append(["Gold", 9])
        else:
            sheet = first
            sheet.title = "Customers"
        for row in rows:
            sheet.append([None if value == "" else value for value in row])
        path = directory / f"{case.name}.xlsx"
        book.save(path)
        return path
    buffer = io.StringIO()
    writer = csv.writer(buffer, delimiter=case.delimiter, lineterminator="\r\n")
    for row in rows:
        writer.writerow([_text(value) for value in row])
    path = directory / f"{case.name}.csv"
    path.write_bytes(buffer.getvalue().encode(case.encoding))
    return path


