def test_no_rate_card_means_no_estimate_and_says_which_file_is_missing() -> None:
    estimate = cost_estimate(compute(), table=None)
    assert estimate.estimated_usd is None
    assert estimate.basis == NO_TABLE
    assert PRICES_FILENAME in estimate.basis


def test_a_job_with_no_billable_time_has_no_estimate(table: PriceTable) -> None:
    """A processing job reports wall clock, and wall clock is not what SageMaker bills (DEC-332)."""
    estimate = cost_estimate(
        compute(backend=PROCESSING_BACKEND, billable_seconds=None, billable_seconds_source=None),
        table=table,
    )
    assert estimate.estimated_usd is None
    assert estimate.basis == NO_BILLABLE_TIME


def test_an_instance_the_card_does_not_price_has_no_estimate_and_names_it(table: PriceTable) -> None:
    estimate = cost_estimate(compute(instance_type="ml.made.up"), table=table)

    assert estimate.estimated_usd is None
    assert estimate.basis == NO_RATE.format(
        component=TRAINING_COMPONENT, instance_type="ml.made.up", region=REGION
    )
    assert "ml.made.up" in estimate.basis and REGION in estimate.basis


def test_a_backend_that_did_not_say_what_it_ran_on_is_a_missing_rate_not_a_missing_time(
    table: PriceTable,
) -> None:
    """The time *was* reported; it is the lookup key that is absent, and the sentence must say so."""
    estimate = cost_estimate(compute(instance_type=None, region=None), table=table)

    assert estimate.estimated_usd is None
    assert estimate.basis != NO_BILLABLE_TIME
    assert UNREPORTED_INSTANCE in estimate.basis
    assert UNREPORTED_REGION in estimate.basis


def test_a_run_nothing_billed_for_has_no_estimate(table: PriceTable) -> None:
    """A fabricated zero is indistinguishable from a real measurement of free compute."""
    estimate = cost_estimate(compute(backend="thread"), table=table)

    assert estimate.estimated_usd is None
    assert estimate.basis == NOT_BILLED


@pytest.mark.parametrize(
    "broken",
    [
        {"backend": "thread"},
        {"instance_type": "ml.made.up"},
        {"billable_seconds": None, "billable_seconds_source": None},
        {"region": "eu-west-1"},
    ],
)
def test_no_path_through_this_module_ever_writes_a_zero(table: PriceTable, broken: dict[str, object]) -> None:
    """`None` is never rounded to zero, because a zero would read as a measurement."""
    estimate = cost_estimate(compute(**broken), table=table)
    assert estimate.estimated_usd is None


def test_a_local_run_reports_its_seconds_and_no_price() -> None:
    estimate = local_cost_estimate(3.14159, basis=NOT_BILLED)
    assert estimate.estimated_usd is None
    assert estimate.compute_seconds == 3.142
    assert estimate.basis == NOT_BILLED


def test_a_zero_second_job_is_still_priced_at_zero_dollars_only_if_aws_said_zero(
    table: PriceTable,
) -> None:
    """Zero billable seconds is a *reported* zero, so the arithmetic may honestly produce zero."""
    estimate = cost_estimate(compute(billable_seconds=0.0), table=table)
    assert estimate.estimated_usd == 0.0
    assert "0 billable seconds" in estimate.basis
