def test_an_sms_variant_without_a_registered_template_is_refused(journey: Journey) -> None:
    approved = _generate_and_approve(journey)
    before = _treat_list(journey)
    url = f"/runs/{journey.run_id}/campaign-copy/variant-arms"

    no_catalogue = journey.client.post(url)
    assert no_catalogue.status_code == 409, no_catalogue.text
    assert no_catalogue.json()["detail"]["code"] == "VARIANT_TEMPLATE_UNREGISTERED"
    assert _reference(approved[0]) in no_catalogue.json()["detail"]["message"]

    # Entered in a catalogue with no region rule, but with no registered template id: refused here.
    _register(journey, approved, dlt=None, region=None)
    unregistered = journey.client.post(url)
    assert unregistered.status_code == 409
    assert unregistered.json()["detail"]["code"] == "VARIANT_TEMPLATE_UNREGISTERED"

    _register(journey, approved, dlt="<your DLT template id>", region=None)  # still the example's placeholder
    placeholder = journey.client.post(url)
    assert placeholder.status_code == 409
    assert placeholder.json()["detail"]["code"] == "VARIANT_TEMPLATE_UNREGISTERED"

    # Under India's region rule (M99) the catalogue itself is refused first, before any arm is drawn.
    _register(journey, approved, dlt=None)
    region_rule = journey.client.post(url)
    assert region_rule.status_code == 422
    assert region_rule.json()["detail"]["code"] == "ACTION_DLT_TEMPLATE_MISSING"

    assert not journey.storage.exists(run_key(journey.run_id, "variant_arms.json"))
    assert not journey.storage.exists(run_key(journey.run_id, "variant_arms.parquet"))
    after = _treat_list(journey)
    assert "variant_arm" not in after.columns
    pd.testing.assert_frame_equal(before, after)


