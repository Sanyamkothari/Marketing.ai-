def test_generate_approve_treat_list_measure_and_proof_pack_per_arm(journey: Journey) -> None:
    approved = _generate_and_approve(journey)
    _register(journey, approved, dlt="1107{index:015d}")
    arms = ok(journey.client.post(f"/runs/{journey.run_id}/campaign-copy/variant-arms"))

    # The arms: M100's treatment-level shape, the control template and both variants.
    assert arms["treatment_levels"] == ["no_message", "control_template", "variant_a", "variant_b"]
    assert arms["control_level"] == "no_message"
    assert {template["dlt_template_id"] for template in arms["templates"]} <= {
        f"1107{index:015d}" for index in range(4)
    }
    shares = (
        np.array([arms["arm_rows"][level] for level in arms["arms"]], dtype=float) / arms["assigned_rows"]
    )
    assert np.all(np.abs(shares - 1 / 3) < 0.04), shares  # equal shares, by each customer's own key

    # The treat list: each treated customer's arm and the approved template it sends on SMS.
    treat_list = _treat_list(journey)
    treated = treat_list["treat"] == 1
    assert treat_list.loc[treated, "variant_arm"].notna().all()
    assert treat_list.loc[~treated, "variant_arm"].isna().all()
    variant_rows = treat_list.loc[treated & treat_list["variant_arm"].isin(["variant_a", "variant_b"])]
    expected = variant_rows["band"] + "-sms-" + variant_rows["variant_arm"].str[-1].str.upper()
    assert (variant_rows["variant_template"] == expected).all()  # the group's own approved template
    assert treat_list.loc[treat_list["variant_arm"] == "control_template", "variant_template"].isna().all()
    assert list(treat_list.columns[-5:]) == [
        "net_value",
        "expected_gross_value",
        "reason_1",
        "reason_2",
        "reason_3",
    ]
    summary = ok(journey.client.get(f"/runs/{journey.run_id}/artefacts/treat_list_summary.json"))
    assert sum(summary["variant_arm_counts"].values()) == int(treated.sum())

    # Measured per arm against the no-message group, and the messages against each other.
    campaign_id, report = _measured_campaign(journey, _outcomes(treat_list, PLANTED, seed=7))
    assert [arm["arm"] for arm in report["arms"]] == ["control_template", "variant_a", "variant_b"]
    assert all(arm["control"] == "no_message" for arm in report["arms"])
    # Measured within the groups the copy was written for: the no-message group is their held-back customers.
    in_groups = treat_list["band"].isin(["High", "Medium"]) & treat_list["suppression_reason"].isna()
    held_back = int((in_groups & (treat_list["control_group"] == 1)).sum())
    assert all(arm["control_rows"] == held_back for arm in report["arms"])
    assert sum(arm["treated_rows"] for arm in report["arms"]) == int(treated.sum())
    assert report["offers_combined"] is not None
    best = report["arms"][2]
    truth = PLANTED["variant_b"] - PLANTED["no_message"]
    assert best["effect"]["ci_low"] <= truth <= best["effect"]["ci_high"]
    import json

    comparison = json.loads(journey.storage.read_bytes(f"campaigns/{campaign_id}/variant_comparison.json"))
    assert comparison["winner"] == "variant_b"
    assert comparison["family_size"] == 3
    margin = comparison["margin"]
    planted_margin = PLANTED["variant_b"] - PLANTED[comparison["closest"]]
    assert margin["ci_low"] > 0 and margin["ci_low"] <= planted_margin <= margin["ci_high"]

    # The Value Proof Pack: a row per message and the winner named, every number traced.
    view = ok(journey.client.get(f"/pilot/proof/{campaign_id}", params={"format": "json"}))
    section = next(item for item in view["sections"] if item["key"] == "incremental")
    assert section["table"]["columns"][0] == "Message"
    assert [row[0]["value"] for row in section["table"]["rows"]] == [
        "control_template",
        "variant_a",
        "variant_b",
    ]
    named = next(line for line in section["lines"] if line["label"] == "Best message")
    assert named["value"]["value"] == "variant_b"
    assert named["value"]["sources"][0]["artefact"].endswith("variant_comparison.json")
    assert_traced(journey.data_dir, view)
    assert_no_stray_digits(journey.client, campaign_id, view)


def test_no_winner_is_named_when_the_messages_do_equally_well(journey: Journey) -> None:
    approved = _generate_and_approve(journey)
    _register(journey, approved, dlt="1107{index:015d}")
    ok(journey.client.post(f"/runs/{journey.run_id}/campaign-copy/variant-arms"))
    campaign_id, report = _measured_campaign(journey, _outcomes(_treat_list(journey), EQUAL, seed=11))
    assert len(report["arms"]) == 3
    view = ok(journey.client.get(f"/pilot/proof/{campaign_id}", params={"format": "json"}))
    section = next(item for item in view["sections"] if item["key"] == "incremental")
    named = next(line for line in section["lines"] if line["label"] == "Best message")
    assert named["value"] is None and named["missing"].startswith("None is named")
    assert_traced(journey.data_dir, view)
