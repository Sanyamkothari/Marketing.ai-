@dataclass(frozen=True)
class Journey:
    client: TestClient
    storage: LocalStorage
    data_dir: Path
    root: Path
    run_id: str


def _config_root(tmp: Path, *, variant_arms: bool, channels: tuple[str, ...] = ("sms",)) -> Path:
    """`configs/` with the win-back use case writing two variants on SMS, and variant arms turned on."""
    root = tmp / "configs"
    shutil.copytree(Path(__file__).resolve().parents[3] / "configs", root)
    path = root / "use_cases" / "win_back_campaign.yaml"
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    generative = document["generative"]
    generative["campaign_copy"]["channels"] = list(channels)
    generative["campaign_copy"]["allowed_fields"] = ["snapshot_date", "band"]  # columns make_run writes
    if variant_arms:
        generative["variant_arms"] = True
    path.write_text(yaml.safe_dump(document, sort_keys=False), encoding="utf-8")
    return root


def _start(
    tmp: Path, *, variant_arms: bool = True, channels: tuple[str, ...] = ("sms",)
) -> Iterator[Journey]:
    root = _config_root(tmp, variant_arms=variant_arms, channels=channels)
    data_dir = tmp / "data"
    data_dir.mkdir()
    storage = LocalStorage(data_dir)
    run_id = write_run(
        storage,
        RunSpec(
            use_case_id=USE_CASE,
            mode=RunMode.SCORE,
            rows=ROWS,
            positive_rate=0.6,
            created_at=SCORED_AT,
            config_root=root,
        ),
    )
    clear_catalogue_cache()
    with TestClient(create_app(config_root=root, data_dir=data_dir)) as client:
        yield Journey(client, storage, data_dir, root, run_id)
    clear_catalogue_cache()


def _generate_and_approve(journey: Journey, *, letters: tuple[str, ...] = ("A", "B")) -> list[dict[str, Any]]:
    client, run_id = journey.client, journey.run_id
    ok(client.post(f"/runs/{run_id}/campaign-copy", json={"overrides": {}}), 202)
    deadline = time.monotonic() + TIMEOUT_S
    while True:
        status = client.get(f"/runs/{run_id}/artefacts/copy_status.json")
        if status.status_code == 200 and status.json()["state"] in ("done", "failed"):
            break
        assert time.monotonic() < deadline, "campaign copy did not finish"
        time.sleep(0.1)
    assert status.json()["state"] == "done", status.json()
    batch = ok(client.get(f"/runs/{run_id}/artefacts/copy_batch.json"))
    approved = []
    for template in batch["templates"]:
        assert template["status"] == "pending_review", template
        if template["variant"] in letters:
            ok(
                client.post(
                    f"/runs/{run_id}/campaign-copy/templates/{template['template_id']}/approve",
                    json={"approved_by": "Asha Rao"},
                )
            )
            approved.append(template)
    return approved


def _reference(template: dict[str, Any]) -> str:
    """The catalogue reference of a template's words, computed independently of the engine."""
    import hashlib

    payload = "\x00".join((template["channel"], template["subject"] or "", template["text"])).encode("utf-8")
    return "copy:" + hashlib.sha256(payload).hexdigest()[:16]


def _register(
    journey: Journey, templates: list[dict[str, Any]], *, dlt: str | None, region: str | None = "IN"
) -> None:
    """Write the client's catalogue: one action per distinct variant text, with its DLT template id."""
    actions = []
    for index, ref in enumerate(sorted({_reference(template) for template in templates})):
        action: dict[str, Any] = {
            "action_id": f"winback_sms_variant_{index}",
            "label": f"Win-back SMS, variant {index}",
            "channels": ["sms"],
            "template_ref": ref,
            "message_category": "promotional",
        }
        if dlt is not None:
            action["dlt_template_id"] = dlt.format(index=index)
        actions.append(action)
    path = journey.root / "decide" / "catalogue.yaml"
    document: dict[str, Any] = (
        {"actions": actions} if region is None else {"region": region, "actions": actions}
    )
    path.write_text(yaml.safe_dump(document, sort_keys=False), encoding="utf-8")
    clear_catalogue_cache()


def _treat_list(journey: Journey) -> pd.DataFrame:
    response = journey.client.get(f"/runs/{journey.run_id}/treat_list.csv")
    assert response.status_code == 200, response.text
    return pd.read_csv(io.StringIO(response.text), dtype={KEY: str})


def _outcomes(treat_list: pd.DataFrame, rates: dict[str, float], *, seed: int) -> pd.DataFrame:
    """The client's outcome file: each customer's outcome at the rate of the arm the treat list gives them."""
    rng = np.random.default_rng(seed)
    arm = treat_list["variant_arm"].where(treat_list["treat"] == 1).fillna("no_message")
    rate = arm.map(rates).to_numpy(dtype=float)
    return pd.DataFrame({KEY: treat_list[KEY], OUTCOME: (rng.random(len(rate)) < rate).astype(int)})


def _measured_campaign(journey: Journey, outcomes: pd.DataFrame) -> tuple[str, dict[str, Any]]:
    client = journey.client
    created = ok(client.post("/campaigns", json={"run_id": journey.run_id}), 201)
    campaign_id = str(created["campaign"]["campaign_id"])
    payload = outcomes.to_csv(index=False, lineterminator="\n").encode()
    upload_id = ok(
        client.post(
            "/uploads",
            files={"file": ("outcomes.csv", payload, "text/csv")},
            data={"use_case": USE_CASE, "mode": "score"},
        ),
        201,
    )["upload_id"]
    ok(
        client.post(
            f"/campaigns/{campaign_id}/outcomes", json={"upload_id": upload_id, "outcome_column": OUTCOME}
        )
    )
    ok(client.post(f"/campaigns/{campaign_id}/measure", json={"as_of": MATURE.isoformat()}))
    report = journey.storage.read_bytes(f"campaigns/{campaign_id}/incrementality_report.json")
    import json

    return campaign_id, dict(json.loads(report))


