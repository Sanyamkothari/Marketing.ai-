"""Plan K M140 through the product's own API: message variants as measured arms (DEC-1407).

The journey is the milestone's: a finished scoring run (written by `tests.fixtures.make_run.write_run`, whose
banding, suppression and control group are the engine's own stages) -> campaign copy generated by the fake
language model (`POST /runs/{id}/campaign-copy`) -> every template approved -> the variants registered in the
catalogue -> variant arms drawn (`POST /runs/{id}/campaign-copy/variant-arms`) -> the treat list downloaded
with each customer's arm -> a campaign opened from the run (`POST /campaigns`), its outcomes added and measured
(`POST /campaigns/{id}/measure`) -> the Value Proof Pack read per arm (`GET /pilot/proof/{id}`).

The outcomes are the only thing the test makes up, as a client's outcome file would be: each customer's
outcome is drawn at the rate planted for the arm the downloaded treat list gives them (no message for the
held-back customers). Checked:

* an SMS variant with no registered template id is refused (`VARIANT_TEMPLATE_UNREGISTERED`), as is one whose
  id is still a placeholder, and nothing is written;
* with one variant approved, nothing changes: the build is refused (`VARIANT_ARMS_NOT_MADE`) and the treat list
  is byte for byte the one built before;
* the arms are the control template and both variants, in equal shares of the customers the copy was written
  for, shown on the treat list for treated customers only, with the template each sends;
* the campaign is measured per arm against the no-message group, every message together, and the messages
  against each other; the planted best variant is named the winner, inside its interval, and the Proof Pack
  shows a row per message and names it, every number traced;
* with no difference planted between the messages, no winner is named;
* arms are kept only while they still hold (review fixes): copy on two channels with no channel per customer is
  refused, as is a treat-list rebuild the run refuses, with no arm file left; regenerating an arm's template,
  writing the copy again, changing the copy behind the routes' back or turning the setting off sets the arms
  aside (the treat list is byte for byte the one without arms, the campaign has none); a campaign with arms
  measured on an amount is measured as a whole; a run with arms is not arbitrated.
"""

