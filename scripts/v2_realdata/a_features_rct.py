def read(spec: Spec, nrows: int | None) -> pd.DataFrame:
    if spec.name == "starbucks":
        a = pd.read_csv(spec.path / "training.csv")
        b = pd.read_csv(spec.path / "Test.csv")
        frame = pd.concat([a, b], ignore_index=True)
        return frame.iloc[:nrows] if nrows else frame
    if spec.name == "criteo":
        dtypes = {f"f{i}": np.float32 for i in range(12)} | {
            "treatment": np.int8,
            "visit": np.int8,
            "conversion": np.int8,
            "exposure": np.int8,
        }
        return pd.read_csv(spec.path, dtype=dtypes, nrows=nrows)
    cols = None
    if spec.name == "lenta":
        cols = [*spec.numeric, *spec.categorical, spec.treatment, *spec.outcomes]
    return pd.read_csv(spec.path, nrows=nrows, usecols=cols)


def brief() -> Brief:
    return Brief(
        brief_id=f"brief_{GOAL}_1",
        goal_id=GOAL,
        objective=Objective.GROSS_PROFIT,
        audience=Audience(description="Everyone in the test"),
        horizon_days=14,
        envelope=Envelope(channels=(Channel.EMAIL,), budget=1e12, max_contacts_per_week=2),
        rationale="Real-data replay",
        created_at=T0 - timedelta(days=30),
        approved_by="realdata",
        approved_at=T0 - timedelta(days=30),
    )


CONTENT = [
    ContentItem(
        content_id="rct_msg",
        goal_id=GOAL,
        channel=Channel.EMAIL,
        theme=Theme.REMINDER,
        body="Offer.",
        status=ContentStatus.APPROVED,
        created_at=T0 - timedelta(days=30),
    )
]


def profile_events(cid: str) -> list[Event]:
    """What the adapter can give the agent: a signup and e-mail consent (invented), nothing else."""
    at = T0 - timedelta(days=200)
    return [
        Event(event_id=f"su_{cid}", customer_id=cid, type=EventType.SIGNUP, ts=at, source="rct"),
        Event(
            event_id=f"co_{cid}",
            customer_id=cid,
            type=EventType.CONSENT_GRANTED,
            ts=at,
            source="rct",
            channel=Channel.EMAIL,
        ),
    ]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset", choices=sorted(_specs()))
    ap.add_argument("--nrows", type=int, default=0)
    ap.add_argument("--seeds", type=int, default=2)
    ap.add_argument("--agent-train", type=int, default=100_000)
    ap.add_argument("--agent-test", type=int, default=50_000)
    ap.add_argument("--variants", default="click,purchase")
    args = ap.parse_args()
    spec = _specs()[args.dataset]
    timings = C.Timings()
    payload: dict[str, object] = {
        "dataset": spec.name,
        "command": " ".join(["python3 -I", *sys.argv]),
        "note": spec.note,
    }

    with timings.step(f"read {spec.name}"):
        frame = read(spec, args.nrows or None)
    n = len(frame)
    arm = (frame[spec.treatment] == spec.treated_value).to_numpy().astype(np.int64)
    share = float(arm.mean())
    if arm.min() == arm.max():
        # Criteo's file is stored in 13 treated/control blocks and rows 1-5,571,799 are all treated,
        # so a head slice (--nrows up to 5.57M) has no control rows and no valid OPE.
        raise SystemExit(
            f"{spec.name}: the first {n} rows hold only one arm (treated share {share}); "
            "no control group, so nothing can be estimated. Use the full file."
        )
    p_t = spec.propensity if spec.propensity is not None else share
    feats = frame[[*spec.numeric, *spec.categorical]].copy()
    ftype = np.float32 if spec.name == "criteo" else np.float64  # 14M rows: keep Criteo light
    for c in spec.numeric:
        feats[c] = pd.to_numeric(feats[c], errors="coerce").astype(ftype).fillna(-1.0)
    for c in spec.categorical:
        feats[c] = feats[c].astype(str)
    # integer row ids; the string customer id is made only for the rows the agent sees
    rct = C.Rct(
        spec.name,
        np.arange(n),
        arm,
        np.where(arm == 1, p_t, 1 - p_t),
        ("control", "treated"),
        feats.reset_index(drop=True),
        {o: frame[o].to_numpy(dtype=np.float64) for o in spec.outcomes},
    )
    del frame
    payload.update(rows=n, treated_share=share, propensity_used=p_t)
    tr_idx, te_idx = C.split_customers(n, seed=0)
    train, test = rct.take(tr_idx), rct.take(te_idx)
    payload["split"] = {"train": train.n, "test": test.n, "seed": 0}
    print(f"{n} rows, treated share {share:.4f} (propensity used {p_t}); train {train.n}, test {test.n}")

    conv = spec.outcomes[-1]
    tr_c = train.outcomes[conv]
    ate = float(tr_c[train.arm == 1].mean() - tr_c[train.arm == 0].mean())
    cost = max(VALUE * ate, 0.001)
    payload["train_ate"] = ate
    payload["break_even_cost"] = cost
    print(f"train ATE on {conv}: {ate:+.5f}; break-even contact cost {cost:.4f}")

    rng = np.random.default_rng(11)
    a_tr = np.sort(rng.permutation(train.n)[: min(args.agent_train, train.n)])
    a_te = np.sort(rng.permutation(test.n)[: min(args.agent_test, test.n)])
    atrain, atest = train.take(a_tr), test.take(a_te)
    prefix = spec.name[:2]
    atrain.customer_ids = np.array([f"{prefix}{int(i)}" for i in atrain.customer_ids])
    atest.customer_ids = np.array([f"{prefix}{int(i)}" for i in atest.customer_ids])

    # the agent: states (prospects with consent), train log
    with timings.step("agent inputs: events and states"):
        ev = [e for c in [*atrain.customer_ids, *atest.customer_ids] for e in profile_events(c)]
        states = C.fold_states(ev, NOW)
    history: dict[str, list[Event]] = {}
    decisions: dict[str, Decision] = {}
    rewards: list[Reward] = []
    for i, cid in enumerate(atrain.customer_ids):
        a = int(atrain.arm[i])
        did = f"rct_{cid}"
        evs = profile_events(cid)
        if a:
            evs.append(
                Event(
                    event_id=f"send_{cid}",
                    customer_id=cid,
                    type=EventType.SEND,
                    ts=T0,
                    source="rct",
                    channel=Channel.EMAIL,
                    decision_id=did,
                    attrs={"content_id": "rct_msg", "logged_probability": float(atrain.propensity[i])},
                )
            )
            if spec.click_outcome and atrain.outcomes[spec.click_outcome][i] > 0:
                evs.append(
                    Event(
                        event_id=f"click_{cid}",
                        customer_id=cid,
                        type=EventType.CLICK,
                        ts=T0 + timedelta(hours=5),
                        source="rct",
                        channel=Channel.EMAIL,
                        decision_id=did,
                    )
                )
            act = Action(goal_id=GOAL, channel=Channel.EMAIL, content_id="rct_msg", send_at=T0)
            decisions[did] = Decision(
                decision_id=did,
                customer_id=cid,
                made_at=T0,
                kind=DecisionKind.ACT,
                action=act,
                group=Group.AGENT,
                probability=float(atrain.propensity[i]),
                reason="RCT",
                policy_version="rct",
            )
        else:
            decisions[did] = Decision(
                decision_id=did,
                customer_id=cid,
                made_at=T0,
                kind=DecisionKind.NOTHING,
                group=Group.HOLDOUT,
                probability=1.0,
                reason="RCT control",
                policy_version="rct",
            )
        history[cid] = evs
        rewards.append(
            Reward(
                decision_id=did,
                customer_id=cid,
                goal_id=GOAL if a else None,
                window_end=T0 + timedelta(days=14),
                converted=bool(atrain.outcomes[conv][i] > 0),
                net=0.0,
            )
        )
    runs = C.run_agent_variants(
        variants=[v for v in args.variants.split(",") if v],
        train=C.TrainLog(history, decisions, rewards),
        train_states=[states[c] for c in atrain.customer_ids],
        test_states=[states[c] for c in atest.customer_ids],
        briefs=[brief()],
        content=CONTENT,
        now=NOW,
        arm_of=lambda d: 0 if d.kind is DecisionKind.NOTHING else 1,
        n_arms=2,
        seeds=list(range(1, args.seeds + 1)),
        costs={Channel.EMAIL: cost},
        horizon_days=14,
        timings=timings,
    )
    payload["agent"] = {v: C.agent_summary(r) for v, r in runs.items()}
    payload["agent_sample"] = {"train": atrain.n, "test": atest.n}

    design = C.Design(numeric=spec.numeric, categorical=spec.categorical)
    rewards_spec = [(o, train.outcomes[o], test.outcomes[o]) for o in spec.outcomes]
    rewards_spec.append(
        ("profit", VALUE * tr_c - cost * train.arm, VALUE * test.outcomes[conv] - cost * test.arm)
    )
    for rname, rew_tr, rew_te in rewards_spec:
        with timings.step(f"baselines for {rname} (fit on {train.n} train rows)"):
            seg_pol, seg_table = C.best_segment_rule(
                train, rew_tr, [list(c) for c in spec.segment_candidates]
            )
            up_pi, _ = C.uplift_t_learner(train, test, rew_tr, design)
            seg_pi = seg_pol(test.logged(rew_te, rname))
        base = {
            "send to none": C.fixed(test.n, 2, 0),
            "send to all": C.fixed(test.n, 2, 1),
            "random 50/50": C.uniform(test.n, 2),
            f"best segment rule ({'+'.join(seg_pol.columns)})": seg_pi,
            "uplift model (T-learner, ridge)": up_pi,
        }
        ref_arm = C.best_blanket_arm(train, rew_tr)
        with timings.step(f"OPE {rname} on the full test split ({test.n} rows)"):
            full = C.evaluate_policies(test, rew_te, rname, base, reference=C.fixed(test.n, 2, ref_arm))
        C.print_table(f"TEST (full) {rname}", full)
        on_sample = {k: v[a_te] for k, v in base.items()}
        for v, run in runs.items():
            on_sample[f"AGENT ({v} model)"] = run.pi
        sample_rows = C.evaluate_policies(
            atest, rew_te[a_te], rname, on_sample, reference=C.fixed(atest.n, 2, ref_arm)
        )
        C.print_table(f"TEST (agent sample, {atest.n} rows) {rname}", sample_rows)
        payload[rname] = {
            "full_test": full,
            "agent_sample": sample_rows,
            "segment_rule_validation": seg_table,
            "best_blanket_arm_on_train": ref_arm,
        }
    payload["timings"] = timings.rows
    C.save(f"a_{spec.name}" + (f"_n{args.nrows}" if args.nrows else ""), payload)


if __name__ == "__main__":
    main()
