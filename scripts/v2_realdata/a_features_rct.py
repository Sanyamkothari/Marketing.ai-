"""RCTs whose customers are only anonymised feature vectors: MegaFon, Starbucks promo, Lenta, Criteo.

    python3 -I scripts/v2_realdata/a_features_rct.py megafon
    python3 -I scripts/v2_realdata/a_features_rct.py starbucks
    python3 -I scripts/v2_realdata/a_features_rct.py lenta
    python3 -I scripts/v2_realdata/a_features_rct.py criteo            # 13,979,592 rows
    # --nrows takes a HEAD slice: fine for megafon/starbucks/lenta, but Criteo's first 5,571,799
    # rows are all treated, so `criteo --nrows N` with N <= 5,571,799 stops with an error.

None of these files has a purchase history, a date or an amount: one row is one customer with
features (`X_1..X_50`, `V1..V7`, Lenta's 193 aggregates, Criteo's `f0..f11`), a randomised treatment
flag and a binary outcome. Autonomy's `CustomerState` has no place for such features (INPUTS.md
section 1), so the agent can only see each customer as a contactable prospect with no history: the
run measures what it does then. The baselines (best segment rule, T-learner uplift model) do read
the features, which is the comparison a customer would care about.

Rewards on TEST (split 50/50 by customer, seed 0):

* the dataset's own outcome (conversion; Criteo also visit);
* profit = 20 x conversion - c x contacted, where 20 is the agent's own default value of a
  prospect's conversion (order value 50 x margin 0.4, `autonomy.decide.models.ValueModel`) and c is
  the break-even contact cost measured on TRAIN (20 x the train ATE): at that cost sending to
  everyone earns nothing on average, so only targeting can make money. The agent is told c.

The agent (both variants, `a_common.run_agent_variants`) learns from at most `--agent-train`
train customers and decides for at most `--agent-test` test customers (sampled at random, seeded);
every policy is then also scored on that same agent sample. Baselines are fitted on the whole train
split and also scored on the whole test split. Results: /home/user/datasets/_results/a_<name>.json.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
